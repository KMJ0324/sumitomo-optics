def to_korean(name: str) -> str:
    """Korean name for a Japanese label, or the label itself if unmapped."""
    if not name:
        return name
    cleaned = str(name).strip()
    # 라벨이 "103_大韓民国" 형태로 올 때를 대비합니다.
    if "_" in cleaned:
        cleaned = cleaned.split("_", 1)[-1]
    return COUNTRY_KO.get(cleaned, cleaned)
